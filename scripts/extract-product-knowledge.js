import esbuild from "esbuild";
import { pathToFileURL } from "node:url";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

// 1. Transpile TS modules using esbuild
const tmp = path.join(os.tmpdir(), `kz-extract-data-${Date.now()}.mjs`);
await esbuild.build({
  stdin: {
    contents: `
      export { products } from "./src/data/products";
      export { typhonProducts } from "./src/data/typhonProducts";
    `,
    resolveDir: process.cwd(),
    loader: "ts",
  },
  bundle: true,
  format: "esm",
  platform: "node",
  outfile: tmp,
  logLevel: "error",
});

const { products, typhonProducts } = await import(pathToFileURL(tmp).href);
fs.rmSync(tmp, { force: true });

function specValue(d, re) {
  if (!d.specs) return undefined;
  return d.specs.find((s) => re.test(s.label))?.value?.trim() || undefined;
}

const allProducts = [...(products || []), ...(typhonProducts || [])];
const normalizedProducts = [];
const missingReport = [];

for (const p of allProducts) {
  const hp = specValue(p, /horsepower|hp/i) || specValue(p, /engine/i)?.match(/(\d+)\s*hp/i)?.[0] || null;
  const engine = specValue(p, /engine/i) || null;
  const weight = p.weight || specValue(p, /weight/i) || null;
  const liftCapacity = specValue(p, /lift capacity|operating capacity|load capacity/i) || null;
  const digDepth = specValue(p, /digging depth|dig depth/i) || null;
  const price = p.price || null;
  const url = p.href || (p.id ? `/typhon-machinery/${p.id}` : null);
  const image = p.image || null;

  // Name normalization
  let cleanName = p.name.trim();
  // Strip duplicate TYPHON prefixes
  cleanName = cleanName.replace(/^(typhon\s+)+/gi, "TYPHON ");
  if (!cleanName.toUpperCase().startsWith("TYPHON") && p.brand === "Typhon") {
    cleanName = "TYPHON " + cleanName;
  }

  normalizedProducts.push({
    id: p.id || p.name.toLowerCase().replace(/\s+/g, "-"),
    name: cleanName,
    brand: p.brand || (cleanName.toUpperCase().includes("TYPHON") ? "Typhon" : "Konstructz"),
    category: p.categoryLabel || "Machinery",
    productType: p.productType || "machine",
    price,
    url,
    image,
    specs: {
      horsepower: hp,
      engine,
      weight,
      liftCapacity,
      digDepth,
    }
  });

  // Calculate missing field report and data quality score
  const missingFields = [];
  if (!hp) missingFields.push("Horsepower");
  if (!engine) missingFields.push("Engine");
  if (!weight) missingFields.push("Weight");
  if (!liftCapacity && (p.categoryLabel || "").toLowerCase().includes("loader")) missingFields.push("Lift Capacity");
  if (!digDepth && (p.categoryLabel || "").toLowerCase().includes("excavator")) missingFields.push("Digging Depth");
  if (!price) missingFields.push("Price");
  if (!url) missingFields.push("Product URL");
  if (!image) missingFields.push("Image");

  const totalChecked = 8;
  const score = Math.round(((totalChecked - missingFields.length) / totalChecked) * 100);

  missingReport.push({
    name: cleanName,
    category: p.categoryLabel || "Machinery",
    missingFields,
    qualityScore: score
  });
}

// Write generated files
fs.writeFileSync(
  path.join(process.cwd(), "productKnowledge.generated.json"),
  JSON.stringify(normalizedProducts, null, 2),
  "utf8"
);

const indexCode = `// Generated by scripts/extract-product-knowledge.js. Do not edit.
export interface NormalizedProduct {
  id: string;
  name: string;
  brand: string;
  category: string;
  productType: string;
  price: string | null;
  url: string | null;
  image: string | null;
  specs: {
    horsepower: string | null;
    engine: string | null;
    weight: string | null;
    liftCapacity: string | null;
    digDepth: string | null;
  };
}

export const normalizedProducts: NormalizedProduct[] = ${JSON.stringify(normalizedProducts, null, 2)};
`;

fs.writeFileSync(
  path.join(process.cwd(), "src/components/chat/chatbotProductIndex.ts"),
  indexCode,
  "utf8"
);

fs.writeFileSync(
  path.join(process.cwd(), "missingProductSpecsReport.json"),
  JSON.stringify(missingReport, null, 2),
  "utf8"
);

// Markdown report generator
let md = `# Missing Product Specifications Audit Report\n\n`;
md += `This report outlines missing fields in the Konstructz/TYPHON Machinery database. Use this to audit and enter missing data.\n\n`;
md += `| Product Name | Category | Missing Fields | Quality Score |\n`;
md += `|---|---|---|---|\n`;

for (const r of missingReport.sort((a, b) => a.qualityScore - b.qualityScore)) {
  const missingText = r.missingFields.length > 0 ? r.missingFields.join(", ") : "None (100% Complete)";
  md += `| ${r.name} | ${r.category} | ${missingText} | ${r.qualityScore}% |\n`;
}

fs.writeFileSync(
  path.join(process.cwd(), "missingProductSpecsReport.md"),
  md,
  "utf8"
);

console.log("Product knowledge normalized and reports written successfully.");
